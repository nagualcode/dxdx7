# Init voice operator overrides: OP1 at full level, the rest silent.
OP_DEFAULT_OVERRIDE = {1: {"level": 99}}


def field(id_, name, short, group, max_, default, kind, fmt, ident):
    attrs = [f"id = {id_}", f'name = "{name}"', f'short_name = "{short}"', f'group = "{group}"']
    if kind == "int":
        attrs.append(f'range = "discrete(0, {max_})"')
        attrs.append(f"default = {default}")
        ty = "IntParam"
    elif kind == "bool":
        attrs.append(f"default = {'true' if default else 'false'}")
        ty = "BoolParam"
    else:
        enum = kind.split(":")[1]
        attrs.append(f"default = {default}")
        ty = f"EnumParam<{enum}>"
    if fmt:
        attrs.append(f'format = "{fmt}"')
    return f"    #[param({', '.join(attrs)})]\n    pub {ident}: {ty},\n"


def value_expr(ident, kind):
    if kind == "int":
        return f"self.{ident}.value() as u8"
    if kind == "bool":
        return f"self.{ident}.value() as u8"
    return f"self.{ident}.index() as u8"


def main():
    out = []
    out.append("// @generated by tools/gen_params.py - do not edit by hand.\n")
    out.append("//! DX7 voice parameters, one host parameter per VCED byte.\n\n")
    out.append("use std::sync::RwLock;\n\nuse truce::prelude::*;\n\n")
    out.append("use crate::enums::*;\nuse crate::state::PatchState;\n\n")
    out.append("#[derive(Params)]\npub struct DxParams {\n")
    out.append("    // ---------------- plugin-level (not part of a DX7 voice) ----------------\n")
    out.append(open_globals())
    out.append("    // ---------------- voice: global ----------------\n")
    for byte, suf, name, short, group, max_, default, kind, fmt in VOICE_FIELDS:
        out.append(field(1000 + byte - 126, name, short, group, max_, default, kind, fmt, suf))
    for n in range(1, 7):
        out.append(f"    // ---------------- OP{n} ----------------\n")
        for k, (suf, name, short, max_, default, kind, fmt) in enumerate(OP_FIELDS):
            d = OP_DEFAULT_OVERRIDE.get(n, {}).get(suf, default)
            out.append(field(100 * n + k, f"OP{n} {name}", short, f"OP{n}", max_, d, kind, fmt, f"op{n}_{suf}"))
        out.append(field(100 * n + 21, f"OP{n} On", "On", f"OP{n}", 1, 1, "bool", None, f"op{n}_on"))
    out.append("\n    /// Cartridge, program number and voice name (strings can't be params).\n")
    out.append('    #[persist = "patch"]\n    pub patch: RwLock<PatchState>,\n\n')
    out.append("    #[meter]\n    pub meter_l: MeterSlot,\n    #[meter]\n    pub meter_r: MeterSlot,\n")
    out.append("}\n\n")

    # read_voice
    out.append("impl DxParams {\n")
    out.append("    /// Snapshot the voice parameters as a 156-byte Dexed patch\n")
    out.append("    /// (155 VCED bytes + operator on/off mask; the name bytes are left alone).\n")
    out.append("    pub fn read_voice(&self, v: &mut [u8; 156]) {\n")
    for n in range(1, 7):
        slot = 6 - n
        for k, (suf, name, short, max_, default, kind, fmt) in enumerate(OP_FIELDS):
            out.append(f"        v[{slot * 21 + k}] = {value_expr(f'op{n}_{suf}', kind)};\n")
    for byte, suf, name, short, group, max_, default, kind, fmt in VOICE_FIELDS:
        out.append(f"        v[{byte}] = {value_expr(suf, kind)};\n")
    mask = " | ".join(f"(u8::from(self.op{n}_on.value()) << {6 - n})" for n in range(1, 7))
    out.append(f"        v[155] = {mask};\n")
    out.append("    }\n}\n\n")

    # id table
    ids = []
    maxes = []
    for b in range(145):
        if b < 126:
            slot, k = divmod(b, 21)
            n = 6 - slot
            ids.append(100 * n + k)
            maxes.append(OP_FIELDS[k][3])
        else:
            ids.append(1000 + b - 126)
            maxes.append(VOICE_FIELDS[b - 126][5])
    out.append("/// Host parameter id of each VCED byte 0..=144.\n")
    out.append(f"pub const VOICE_PARAM_IDS: [u32; 145] = {fmt_list(ids)};\n\n")
    out.append("/// Maximum value of each VCED byte 0..=144.\n")
    out.append(f"pub const VOICE_PARAM_MAX: [u8; 145] = {fmt_list(maxes)};\n\n")
    out.append("/// Host parameter id of the on/off switch of OP1..OP6.\n")
    out.append(f"pub const OP_ON_IDS: [u32; 6] = {fmt_list([100 * n + 21 for n in range(1, 7)])};\n\n")
    out.append("/// Host parameter id of byte `k` (0..=20) of operator `n` (1..=6).\n")
    out.append("pub const fn op_param_id(n: usize, k: usize) -> u32 {\n    (100 * n + k) as u32\n}\n\n")
    out.append("/// Host parameter id of voice byte 126..=144.\n")
    out.append("pub const fn voice_param_id(byte: usize) -> u32 {\n    (1000 + byte - 126) as u32\n}\n")
    print("".join(out), end="")


def fmt_list(xs):
    body = ", ".join(str(x) for x in xs)
    # wrap at ~96 columns
    lines, cur = [], "    "
    for tok in body.split(", "):
        if len(cur) + len(tok) + 2 > 96:
            lines.append(cur.rstrip())
            cur = "    "
        cur += tok + ", "
    lines.append(cur.rstrip())
    return "[\n" + "\n".join(lines) + "\n]"


