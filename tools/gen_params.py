"""Generate src/params.rs: every DX7 voice parameter as a host parameter.

The DX7 voice (VCED, 155 bytes, plus Dexed's operator on/off byte at 156)
is exposed one host parameter per byte so that every value is automatable
and saved with the DAW project. Ids are fixed forever (hosts store
automation by id):

    OPn byte k   -> id 100*n + k      (n = 1..6, k = 0..20)
    OPn on/off   -> id 100*n + 21
    voice byte b -> id 1000 + (b - 126)   (b = 126..144: pitch EG, algorithm,
                                            feedback, LFO, transpose)
    plugin-level -> ids 1..99 (written by hand below; 90..95 = hidden MIDI proxies)

The patch byte layout follows the DX7 VCED / Dexed order: operator slot 0 is
OP6, slot 5 is OP1.

Run:  python3 tools/gen_params.py > src/params.rs
"""

